CREATE TABLE IF NOT EXISTS products (
 id TEXT PRIMARY KEY NOT NULL, name TEXT NOT NULL, category TEXT NOT NULL,
 price_cents INTEGER NOT NULL, quantity INTEGER NOT NULL DEFAULT 1,
 description TEXT NOT NULL, fulfillment TEXT NOT NULL, image_key TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'draft', created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS settings (id TEXT PRIMARY KEY NOT NULL, value TEXT NOT NULL);
